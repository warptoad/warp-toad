/**
 * Query Burn events from L1WarpToad to get all commitments
 */
async function getBurnEvents(
	publicClient: PublicClient,
	warpToadAddress: string,
	chainId: number,
	toBlock: bigint | 'latest' = 'latest'
): Promise<Array<{ commitment: bigint; amount: bigint; index: number }>> {
	const fromBlock = getDeploymentBlock(chainId);
	const lastBlock = toBlock === 'latest' ? undefined : toBlock;

	const logs = await queryEventInChunks({
		publicClient,
		contract: { address: warpToadAddress as `0x${string}`, abi: L1WarpToadAbi },
		eventName: 'Burn',
		firstBlock: fromBlock,
		lastBlock,
	});

	return logs.map((log: any) => ({
		commitment: log.args.commitment as bigint,
		amount: log.args.amount as bigint,
		index: Number(log.args.index),
	}));
}

/**
 * Query ReceivedNewLocalRoot events from GigaBridge
 * 
 * Event signature: ReceivedNewLocalRoot(uint256 indexed newLocalRoot, uint40 indexed localRootIndex, uint256 localRootBlockNumber)
 */
async function getLocalRootEvents(
	publicClient: PublicClient,
	gigaBridgeAddress: string,
	chainId: number,
	toBlock: bigint | 'latest' = 'latest'
): Promise<Array<{ localRoot: bigint; index: number; blockNumber: number; eventBlockNumber: bigint }>> {
	const fromBlock = getDeploymentBlock(chainId);
	const lastBlock = toBlock === 'latest' ? undefined : toBlock;

	// Reverse-scan with a small cap so we don't rescan ~700k blocks every time.
	// We only need the LATEST event per local-root index to reconstruct the
	// giga tree leaves; in practice recent updateGigaRoot calls emit all
	// three leaves close together near `toBlock`, so a handful of chunks
	// already fills the window. The cap is generous enough to tolerate
	// skewed emission (e.g. aztec leaf updated long before scroll leaf).
	const logs = await queryEventInChunks({
		publicClient,
		contract: { address: gigaBridgeAddress as `0x${string}`, abi: GigaBridgeAbi },
		eventName: 'ReceivedNewLocalRoot',
		firstBlock: fromBlock,
		lastBlock,
		reverseOrder: true,
		maxEvents: 30,
	});

	return logs.map((log: any) => ({
		localRoot: log.args.newLocalRoot as bigint,
		index: Number(log.args.localRootIndex),
		blockNumber: Number(log.args.localRootBlockNumber),
		eventBlockNumber: log.blockNumber,
	}));
}

/**
 * Find the most recent ReceivedNewLocalRoot event for one provider index at or
 * before `upToBlock`. GigaBridge.updateGigaRoot only emits the event for the
 * providers passed into that call; other providers' local roots stay in the
 * tree from earlier updates. To reconstruct the leaves of a historical
 * gigaRoot we must walk the log backwards per index, not just look at events
 * emitted in the construction block.
 */
export async function getLatestLocalRootEventForIndex(
	publicClient: PublicClient,
	gigaBridgeAddress: string,
	chainId: number,
	index: number,
	upToBlock: bigint
): Promise<{ localRoot: bigint; index: number; blockNumber: number; eventBlockNumber: bigint } | null> {
	const fromBlock = getDeploymentBlock(chainId);
	const logs = await queryEventInChunks({
		publicClient,
		contract: { address: gigaBridgeAddress as `0x${string}`, abi: GigaBridgeAbi },
		eventName: 'ReceivedNewLocalRoot',
		eventFilterArgs: { localRootIndex: BigInt(index) } as any,
		firstBlock: fromBlock,
		lastBlock: upToBlock,
		reverseOrder: true,
		maxEvents: 1,
	});

	if (logs.length === 0) return null;
	const log = logs[logs.length - 1] as any;
	return {
		localRoot: log.args.newLocalRoot as bigint,
		index: Number(log.args.localRootIndex),
		blockNumber: Number(log.args.localRootBlockNumber),
		eventBlockNumber: log.blockNumber,
	};
}

/**
 * Query ConstructedNewGigaRoot events from GigaBridge
 * @param filterGigaRoot - If provided, only returns events for this specific gigaRoot value
 */
async function getGigaRootEvents(
	publicClient: PublicClient,
	gigaBridgeAddress: string,
	chainId: number,
	filterGigaRoot?: bigint
): Promise<Array<{ gigaRoot: bigint; blockNumber: bigint; transactionHash: `0x${string}` }>> {
	const fromBlock = getDeploymentBlock(chainId);

	// When filtering for a specific gigaRoot, scan backwards and stop at the first
	// hit - the event is emitted once and we don't need to scan deployment → head.
	const logs = await queryEventInChunks({
		publicClient,
		contract: { address: gigaBridgeAddress as `0x${string}`, abi: GigaBridgeAbi },
		eventName: 'ConstructedNewGigaRoot',
		eventFilterArgs: filterGigaRoot ? { newGigaRoot: filterGigaRoot } : undefined,
		firstBlock: fromBlock,
		reverseOrder: filterGigaRoot !== undefined,
		maxEvents: filterGigaRoot !== undefined ? 1 : Infinity,
	});

	return logs.map((log: any) => ({
		gigaRoot: log.args.newGigaRoot as bigint,
		blockNumber: log.blockNumber,
		transactionHash: log.transactionHash,
	}));
}

