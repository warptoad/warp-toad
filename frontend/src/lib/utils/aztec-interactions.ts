/**
 * Poseidon2 hash with separator (for Aztec note hashing)
 * Uses @zkpassport/poseidon2 which is compatible with Aztec's poseidon2
 */
async function poseidon2HashWithSeparator(inputs: bigint[], separator: bigint): Promise<bigint> {
	// Import dynamically since it's an async module
	//@ts-ignore
	const { poseidon2Hash } = await import('@zkpassport/poseidon2');
	const inputsWithSeparator = [separator, ...inputs];
	return poseidon2Hash(inputsWithSeparator);
}

/**
 * Compute note hash nonce (for Aztec note siloing)
 */
async function hashNoteHashNonce(firstNullifierInTx: bigint, noteIndexInTx: bigint): Promise<bigint> {
	return poseidon2HashWithSeparator([firstNullifierInTx, noteIndexInTx], GENERATOR_INDEX__NOTE_HASH_NONCE);
}

/**
 * Compute siloed note hash (contract address + plain note hash)
 */
async function hashSiloedNoteHash(contractAddress: bigint, plainNoteHash: bigint): Promise<bigint> {
	return poseidon2HashWithSeparator([contractAddress, plainNoteHash], GENERATOR_INDEX__SILOED_NOTE_HASH);
}

/**
 * Compute unique note hash (nonce + siloed note hash)
 */
async function hashUniqueNoteHash(nonce: bigint, siloedNoteHash: bigint): Promise<bigint> {
	return poseidon2HashWithSeparator([nonce, siloedNoteHash], GENERATOR_INDEX__UNIQUE_NOTE_HASH);
}

/**
 * Get Aztec merkle data for a commitment
 * 
 * This is needed for Aztec -> L1 withdrawals. The function:
 * 1. Queries the contract to find the note with matching commitment
 * 2. Gets the note's nonce from metadata
 * 3. Computes the siloed and unique note hash (as Aztec does)
 * 4. Gets the merkle proof from the note hash tree
 * 
 * @param wallet - Connected Aztec wallet
 * @param commitment - The commitment hash (plain note hash before siloing)
 * @param blockNumber - Aztec block number when the commitment was created
 * @returns Merkle data for the withdraw circuit
 */
export async function getAztecMerkleData(
	wallet: Wallet,
	commitment: bigint,
	blockNumber: number
): Promise<AztecMerkleData> {
	console.log('Getting Aztec merkle data for commitment:', commitment.toString().slice(0, 20) + '...');
	console.log('Block number:', blockNumber);

	const contract = await getWarpToadContract(wallet);
	const accounts = await wallet.getAccounts();
	const from = accounts[0].item;

	// Step 1: Get notes from the contract to find the note nonce
	// The contract has a utility function that returns notes from the commitments storage
	console.log('Fetching notes from contract...');
	// Use get_notes_with_nonces (read-only) instead of get_notes_util (which nullifies!).
	// Returns BoundedVec<{ note: WarpToadNote, note_nonce: Field }, 16>.
	const contractNotesSim = await contract.methods
		.get_notes_with_nonces(contract.artifact.storageLayout.commitments.slot)
		.simulate({ from }) as any;
	const contractNotes = contractNotesSim.result ?? contractNotesSim;

	console.log('Retrieved', contractNotes.storage.length, 'notes');

	// Step 2: Collect ALL notes matching the commitment. The same
	// (nullifier_preimage, secret, chain_id, amount) tuple can exist multiple times
	// (e.g. stale + fresh burn entries), so we gather them all and try each one's
	// unique note hash against the merkle tree, preferring the most recent first.
	const matchingNonces: bigint[] = [];
	for (const entry of contractNotes.storage) {
		const noteCommitment = hashCommitment(
			hashPreCommitment(
				BigInt(entry.note.nullifier_preimage.toString()),
				BigInt(entry.note.secret.toString()),
				BigInt(entry.note.chain_id.toString())
			),
			BigInt(entry.note.amount.toString())
		);
		if (noteCommitment === commitment) {
			matchingNonces.push(BigInt(entry.note_nonce.toString()));
		}
	}
	console.log(`Found ${matchingNonces.length} note(s) matching commitment`);
	// Try most recent first (storage order tends to be append-only, so reverse).
	matchingNonces.reverse();
	const noteNonce: bigint | null = matchingNonces[0] ?? null;

	if (noteNonce === null) {
		throw new Error(
			`Could not find note with commitment ${commitment.toString().slice(0, 20)}... ` +
			'The note may not be synced to this wallet yet, or the commitment data is incorrect.'
		);
	}

	// Step 3: Compute the siloed and unique note hash
	const warpToadAddressStr = AZTEC_CONTRACTS.AztecWarpToad.address;
	const contractAddressBigInt = BigInt(AztecAddress.fromString(warpToadAddressStr).toBigInt());

	const siloedNoteHash = await hashSiloedNoteHash(contractAddressBigInt, commitment);
	console.log('Siloed note hash:', siloedNoteHash.toString().slice(0, 20) + '...');

	// Step 4: Query the Aztec node directly for the membership witness.
	//
	// Earlier versions called `contract.methods.get_note_proof(...).simulate()`,
	// which routes through PXE's private-function simulator. That path picks
	// an "anchor block" based on PXE's local chain view and then asks the node
	// for state at `blockNumber` constrained to that anchor hash. On testnet
	// the anchor hash that PXE settles on is not always one the node will
	// recognise (proven tip drift, partial sync, etc.), producing cryptic
	// "Block hash X not found in world state at block number N" errors even
	// after a full PXE reset.
	//
	// `aztecNode.getNoteHashMembershipWitness` skips PXE entirely: the node
	// computes the witness against its own canonical view of `blockNumber`.
	// Returns undefined when the leaf isn't in the tree at that block, which
	// is the signal to try the next candidate nonce (same UX as before).
	const node = await getAztecNode();
	let witness: { leafIndex: bigint; siblingPath: readonly { toString(): string }[] } | null = null;
	let usedNonce: bigint = noteNonce;
	let lastErr: unknown = null;
	for (const candidateNonce of matchingNonces) {
		const uniqueNoteHash = await hashUniqueNoteHash(candidateNonce, siloedNoteHash);
		console.log(`Trying nonce ${candidateNonce.toString().slice(0, 12)}... → uniqueHash ${uniqueNoteHash.toString().slice(0, 20)}... at block=${blockNumber}`);
		try {
			const uniqueNoteHashFr = Fr.fromString('0x' + uniqueNoteHash.toString(16).padStart(64, '0'));
			const w = await (node as any).getNoteHashMembershipWitness(blockNumber, uniqueNoteHashFr);
			if (w) {
				witness = w;
				usedNonce = candidateNonce;
				console.log(`  ✓ found in tree at leafIndex ${(w as any).leafIndex?.toString()}`);
				break;
			}
			console.log(`  ✗ not in tree at block ${blockNumber}, trying next candidate`);
		} catch (e) {
			console.log(`  ✗ node error for candidate nonce:`, (e as Error)?.message ?? e);
			lastErr = e;
		}
	}
	if (!witness) {
		throw lastErr ?? new Error(`No matching note found in note hash tree at block ${blockNumber}`);
	}

	console.log('Retrieved merkle witness with index:', witness.leafIndex.toString());

	// Step 5: Format the merkle data for the circuit.
	const merkleData: AztecMerkleData = {
		leaf_index: BigInt(witness.leafIndex.toString()),
		hash_path: witness.siblingPath.map((h) => BigInt(h.toString())),
		leaf_nonce: usedNonce,
		contract_address: contractAddressBigInt,
	};

	console.log('Aztec merkle data generated successfully');
	return merkleData;
}

